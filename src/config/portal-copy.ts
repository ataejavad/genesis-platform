export const NUM_LOCALE: Record<string, string> = { it: "it-IT", de: "de-DE", en: "en-GB", fa: "fa-IR" };
// "always" grouping: Node and browsers ship different locale data, and server and browser must print the same.
// (the lib typings of this TypeScript version only know a boolean here)
const ALWAYS = { useGrouping: "always" } as unknown as Intl.NumberFormatOptions;
export const fmtEur = (n: number, lang: string) => new Intl.NumberFormat(NUM_LOCALE[lang] ?? "en-GB", { style: "currency", currency: "EUR", maximumFractionDigits: 0, ...ALWAYS }).format(n);
export const fmtNum = (n: number, lang: string) => new Intl.NumberFormat(NUM_LOCALE[lang] ?? "en-GB", { maximumFractionDigits: 1, ...ALWAYS }).format(n);
