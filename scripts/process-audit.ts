// `npm run audit:process`: the process map (src/config/process-map.ts) against the code.
// Fails (exit 1) when a handoff goes nowhere or the map points at code that does not exist.
// Writes docs/process-audit.md: founder's manual steps and every open gap, ranked by impact.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { LOG_ONLY, STEPS, type Step } from "../src/config/process-map";

const read = (p: string) => readFileSync(p, "utf8");
const errors: string[] = [];

// 1. Every event type the code can emit must be consumed by a step of the map (or be log-only with a reason).
const eventTypes = [...read("src/server/events.ts").matchAll(/^\s*\|\s*"([a-z_.]+)"/gm)].map((m) => m[1]);
const triggers = new Map<string, Step[]>();
for (const s of STEPS) if (s.trigger.startsWith("event:")) triggers.set(s.trigger.slice(6), [...(triggers.get(s.trigger.slice(6)) ?? []), s]);
for (const t of eventTypes) if (!triggers.has(t) && !LOG_ONLY[t]) errors.push(`event "${t}" is emitted but no step in the process map consumes it`);
for (const t of triggers.keys()) if (t !== "*" && !eventTypes.includes(t)) errors.push(`map step listens to "${t}", which the code never emits`);

// 2. Handlers named in the map exist.
for (const s of STEPS) {
  if (!s.handler) {
    if (s.by !== "planned") errors.push(`${s.id}: ${s.by} step without a handler`);
    continue;
  }
  const [file, fn] = s.handler.split("#");
  if (!existsSync(file)) errors.push(`${s.id}: handler file ${file} not found`);
  else if (fn && !new RegExp(`(function|const)\\s+${fn}\\b`).test(read(file))) errors.push(`${s.id}: ${fn} not found in ${file}`);
  if (s.by === "planned" && !s.step) errors.push(`${s.id}: planned step needs the build step that adds it`);
}

// 3. Human steps with a promise to someone must be watched, or they stall silently.
for (const s of STEPS) if (s.by === "human" && s.sla && !s.watch) errors.push(`${s.id}: human step with SLA ${s.sla} but nothing watches it`);
const ids = new Set<string>();
for (const s of STEPS) (ids.has(s.id) ? errors.push(`duplicate step id ${s.id}`) : ids.add(s.id));

// 4. Report.
const rank = (s: Step) => (s.impact ?? 9) * 10 + (s.by === "planned" ? 0 : 1);
const gaps = STEPS.filter((s) => s.gap).sort((a, b) => rank(a) - rank(b));
const human = STEPS.filter((s) => s.by === "human");
const deadEnds = eventTypes.filter((t) => (triggers.get(t) ?? []).every((s) => s.by === "planned") && !LOG_ONLY[t]);
const byFlow = [...new Set(STEPS.map((s) => s.flow))].map((f) => {
  const st = STEPS.filter((s) => s.flow === f);
  const n = (b: string) => st.filter((s) => s.by === b).length;
  return `| ${f} | ${st.length} | ${n("auto")} | ${n("human")} | ${n("planned")} | ${st.filter((s) => s.gap).length} |`;
});
const md = [
  "# Process audit",
  "",
  "Generated by `npm run audit:process` from `src/config/process-map.ts`. Do not edit by hand.",
  "",
  `**${STEPS.length} steps · ${STEPS.filter((s) => s.by === "auto").length} automatic · ${human.length} by a person · ${STEPS.filter((s) => s.by === "planned").length} not built · ${gaps.length} open gaps (${gaps.filter((g) => g.impact === 1).length} costing customers or money now)**`,
  "",
  "| Flow | Steps | Auto | Person | Not built | Gaps |",
  "|---|---|---|---|---|---|",
  ...byFlow,
  "",
  "## Open gaps, ranked (1 = costs customers or money now)",
  "",
  "| # | Impact | Step | Who → whom | Gap | Fixed in |",
  "|---|---|---|---|---|---|",
  ...gaps.map((g, i) => `| ${i + 1} | ${g.impact ?? "?"} | ${g.id} | ${g.edge} | ${g.gap} | ${g.step ? `step ${g.step}` : g.by === "human" ? "automate" : "—"} |`),
  "",
  "## Events that reach no running code yet (dead ends until their step is built)",
  "",
  deadEnds.length ? deadEnds.map((t) => `- \`${t}\` → ${(triggers.get(t) ?? []).map((s) => `${s.id} (step ${s.step})`).join(", ")}`).join("\n") : "None.",
  "",
  "## Steps a person does today (founder load)",
  "",
  ...human.map((s) => `- **${s.id}** (${s.edge}): ${s.does}${s.sla ? ` · promise ${s.sla}` : ""}${s.watch ? ` · watched by ${s.watch}` : " · **unwatched**"}`),
  "",
].join("\n");
writeFileSync("docs/process-audit.md", md);

console.log(`process audit: ${STEPS.length} steps, ${human.length} manual, ${gaps.length} gaps, ${deadEnds.length} dead-end events → docs/process-audit.md`);
if (errors.length) {
  console.error(`\n${errors.length} problem(s):\n- ${errors.join("\n- ")}`);
  process.exit(1);
}
